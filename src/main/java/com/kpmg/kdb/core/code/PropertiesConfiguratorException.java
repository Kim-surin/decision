package com.kpmg.kdb.core.code;

public class PropertiesConfiguratorException extends Exception {
	
	private static final long serialVersionUID = -6148043817176510024L;
	
    
    public PropertiesConfiguratorException() {
        super();
    }

    
    public PropertiesConfiguratorException(String msg) {
        super(msg);
    }

    
    public PropertiesConfiguratorException(Throwable cause) {
        super(cause);
    }

    public PropertiesConfiguratorException(String msg, Throwable cause) {
        super(msg, cause);
    }
}
