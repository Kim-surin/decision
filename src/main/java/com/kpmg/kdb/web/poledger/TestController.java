	/**
	 * 개별판정 배치 처리(Option A) 테스트 엔드포인트. 원본 (SALES_NO, PRODUCT_CODE) 행 목록을
	 * {@link com.kpmg.kdb.web.origindecision.IndividualDecisionGroupingService} 로
	 * CUSTOMER_CODE+DIVISION_CODE+YYYYMM+COMPANY_CODE 기준 그룹핑하고, 그룹마다
	 * {@link com.kpmg.kdb.web.origindecision.OriginDecisionPipeline} 을 새로 만들어 가상매출 생성부터
	 * STATUS 업데이트까지 수행한다({@link IndividualBulkDecisionService} 참고).
	 *
	 * <p>mock 데이터는 501건이며, 그룹핑 기준(CUSTOMER_CODE+DIVISION_CODE+YYYYMM+COMPANY_CODE)으로
	 * 나누면 23개 그룹이 나온다. customerCode=1248533444(FRT100) 가 대부분이지만 6208500010,
	 * 1068197118, 3108112926 등 다른 CUSTOMER_CODE 도 섞여 있어 그룹 분리 여부를 함께 검증할 수 있고,
	 * yyyymm=202402 는 CUSTOMER_CODE 만 다른(1248533444 vs 3108112926) 두 그룹으로 정확히 나뉘는지
	 * 확인하는 케이스다. 그중 companyCode=FRT100/customerCode=1248533444/yyyymm=202604 그룹이 가장
	 * 복잡한데, PRODUCT_CODE 7종(09100DE000/DE200/AT150/AT050/H8370/H8470/AT100)이 섞여 있고
	 * PRODUCT_CODE=09100AT050 은 SALES_NO 9건에 걸쳐 중복 등장하므로 그중 가장 먼저 나온
	 * SALES_NO=202604302648 만 대표로 남는지 확인한다.
	 */
	@RequestMapping(value = "/origin/compliance/test/individual-bulk-decision")
	@ResponseBody
	public Result runIndividualBulkDecision() {
		Result result = new Result();
		try {
			String companyCode = "FRT100";
			List<IndividualDecisionRawLine> rawLines = buildIndividualBulkMockLines();

			BulkDecisionResult bulkResult = individualBulkDecisionService
					.run(new IndividualBulkDecisionRequest(companyCode, rawLines));

			result.setSuccess(bulkResult.getFailedTargets().isEmpty());
			result.setMessage(bulkResult.getFailedTargets().isEmpty() ? "개별판정 배치 완료" : "일부 판정대상 실패 - value 확인");
			result.setValue(describeResult(bulkResult));
		} catch (Exception e) {
			logger.error("개별판정 배치 테스트 실행 중 오류", e);
			result.setSuccess(false);
			result.setMessage("개별판정 배치 테스트 실행 중 오류: " + e.getMessage());
		}
		return result;
	}

	/**
	 * 월판정(MONTHLY_DECISION_PROC 이관) 배치 테스트 엔드포인트. companyCode/yyyymmdd 만 지정하고
	 * divisionCode/customerCode/deliveryCustomerCode/productCodes 는 모두 비워, {@link
	 * MonthlyBulkDecisionService} 가 해당 회사·기간의 내수(EXPORT_FLAG='D', 고객사/사업부 그룹마다
	 * 가상매출 생성 후 판정)와 수출(EXPORT_FLAG='E', 이미 TARGET_FTA_CODE 가 세팅된 실제 매출 판정)을
	 * 모두 처리하도록 한다 — 레거시 판정대상 커서(C_SALES_MST)가 두 흐름을 한 번에 순회하던 것과 동일한
	 * 범위다.
	 *
	 * companyCode=FRT100, yyyymmdd=202604(2026년 4월).
	 */
	@RequestMapping(value = "/origin/compliance/test/monthly-decision")
	@ResponseBody
	public Result runMonthlyDecision() {
		Result result = new Result();
		try {
			VirtualSalesGenerationParams filter = new VirtualSalesGenerationParams();
			filter.setCompanyCode("FRT100");
			filter.setYyyymmdd("202604");

			BulkDecisionResult bulkResult = monthlyBulkDecisionService.run(filter);

			result.setSuccess(bulkResult.getFailedTargets().isEmpty());
			result.setMessage(bulkResult.getFailedTargets().isEmpty() ? "월판정 배치 완료" : "일부 판정대상 실패 - value 확인");
			result.setValue(describeResult(bulkResult));
		} catch (Exception e) {
			logger.error("월판정 배치 테스트 실행 중 오류", e);
			result.setSuccess(false);
			result.setMessage("월판정 배치 테스트 실행 중 오류: " + e.getMessage());
		}
		return result;
	}

	/**
	 * 수출 개별판정 배치 테스트 엔드포인트. 내수 개별판정과 달리 이미 존재하는 실제 SALES_NO 를 그대로
	 * 대상으로 삼아 가상매출을 새로 만들 필요가 없으므로, {@link ExportDecisionTarget} 목록(이미 확정된
	 * companyCode/divisionCode/salesNo/productCodes 조합)을 그대로 넘긴다 — 그룹핑(데이터 가공) 단계가
	 * 없다({@link ExportBulkDecisionService} 참고).
	 *
	 * companyCode=MRV100, divisionCode=MRV101, salesNo=2026040858, productCodes=null(전체 제품).
	 */
	@RequestMapping(value = "/origin/compliance/test/export-bulk-decision")
	@ResponseBody
	public Result runExportBulkDecision() {
		Result result = new Result();
		try {
			List<ExportDecisionTarget> targets = List.of(new ExportDecisionTarget("MRV100", "MRV101", "2026040858", null));

			BulkDecisionResult bulkResult = exportBulkDecisionService.run(targets);

			result.setSuccess(bulkResult.getFailedTargets().isEmpty());
			result.setMessage(bulkResult.getFailedTargets().isEmpty() ? "수출 개별판정 배치 완료" : "일부 판정대상 실패 - value 확인");
			result.setValue(describeResult(bulkResult));
		} catch (Exception e) {
			logger.error("수출 개별판정 배치 테스트 실행 중 오류", e);
			result.setSuccess(false);
			result.setMessage("수출 개별판정 배치 테스트 실행 중 오류: " + e.getMessage());
		}
		return result;
	}

	private Map<String, Object> describeResult(BulkDecisionResult bulkResult) {
		Map<String, Object> value = new LinkedHashMap<>();
		value.put("groupCount", bulkResult.getGroupCount());
		value.put("targets", bulkResult.getTargets().stream().map(this::describeTarget).collect(Collectors.toList()));
		value.put("failedTargets",
				bulkResult.getFailedTargets().stream().map(this::describeTarget).collect(Collectors.toList()));
		return value;
	}

	private String describeTarget(SalesTarget target) {
		return target.getCompanyCode() + "/" + target.getDivisionCode() + "/" + target.getSalesNo();
	}

